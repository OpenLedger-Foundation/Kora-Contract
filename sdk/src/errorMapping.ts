export function getErrorMessage(code: number, contract?: string): string | undefined {
  if (contract) {
    const normalized = contract.toLowerCase().replace(/[-_]/g, "");
    if (normalized.includes("dispute") || normalized.includes("escrow")) {
      return DISPUTE_ESCROW_ERROR_MESSAGES[code];
    }
    if (normalized.includes("fractional")) {
      return FRACTIONALIZER_ERROR_MESSAGES[code];
    }
    if (normalized.includes("secondary")) {
      return SECONDARY_MARKET_ERROR_MESSAGES[code];
    }
    if (normalized.includes("governance") || normalized.includes("voting")) {
      return GOVERNANCE_VOTING_ERROR_MESSAGES[code];
    }
  }
  return CONTRACT_ERROR_MESSAGES[code];
}
