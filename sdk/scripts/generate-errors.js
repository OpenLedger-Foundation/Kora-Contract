#!/usr/bin/env node
// Generates src/contractErrors.ts from the contracts' #[contracterror] enums.
// Usage: node scripts/generate-errors.js [--check]
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "../../contracts");
const out = path.join(__dirname, "../src/contractErrors.ts");

function generate() {
  const tables = {};
  for (const dir of fs.readdirSync(root).sort()) {
    const file = path.join(root, dir, "src", dir === "shared" ? "errors.rs" : "lib.rs");
    if (["fuzz", "tests", "xtask"].includes(dir) || !fs.existsSync(file)) continue;
    const src = fs.readFileSync(file, "utf8").replace(/\/\/.*$/gm, "");
    const re = dir === "shared"
      ? /#\[contracterror[^\]]*\](?:\s*#\[[^\]]*\])*\s*pub enum (KoraError)\s*\{([^}]*)\}/
      : /#\[contracterror[^\]]*\](?:\s*#\[[^\]]*\])*\s*pub enum (\w+)\s*\{([^}]*)\}/;
    const m = re.exec(src);
    if (!m) continue;
    tables[dir] = [...m[2].matchAll(/(\w+)\s*=\s*(\d+)/g)].map((v) => [Number(v[2]), v[1]]);
  }
  // Marketplace has no local enum: its entrypoints return the shared KoraError.
  const marketplace = fs.readFileSync(path.join(root, "marketplace/src/lib.rs"), "utf8");
  if (!tables.marketplace && /Result<[^>]*KoraError>/.test(marketplace)) {
    tables.marketplace = tables.shared;
  }
  const names = [...new Set(Object.values(tables).flat().map(([, n]) => n))].sort();
  return [
    "// Generated by scripts/generate-errors.js. Do not edit by hand.",
    "",
    "/** Stable, contract-independent error identifiers. */",
    "export enum KoraErrorCode {",
    ...names.map((n) => `  ${n} = "${n}",`),
    '  Unknown = "Unknown",',
    "}",
    "",
    "/** On-chain code to SDK enum, per contract. `shared` is the master registry. */",
    "export const CONTRACT_ERROR_CODES = {",
    ...Object.entries(tables).flatMap(([dir, rows]) => [
      `  ${dir}: {`,
      ...rows.map(([c, n]) => `    ${c}: KoraErrorCode.${n},`),
      "  },",
    ]),
    "} as const;",
    "",
    "export type KoraContractName = keyof typeof CONTRACT_ERROR_CODES;",
    "",
  ].join("\n");
}

if (require.main === module) {
  const text = generate();
  if (!process.argv.includes("--check")) fs.writeFileSync(out, text);
  else if (fs.readFileSync(out, "utf8") !== text) {
    console.error("src/contractErrors.ts is stale; run npm run generate:errors");
    process.exitCode = 1;
  }
}
module.exports = { generate };
